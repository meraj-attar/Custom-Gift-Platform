def seed_database() -> None:
    db = SessionLocal()
    try:
        admin = db.scalar(select(User).where(User.email == settings.admin_email.lower()))
        if not admin:
            db.add(User(
                name=settings.admin_name,
                email=settings.admin_email.lower(),
                password_hash=hash_password(settings.admin_password),
                role="admin",
                is_active=True,
            ))

        # Add only products that are missing so this seed can safely be rerun
        # against an existing development database after the catalog grows.
        for data in SEED_PRODUCTS:
            existing = db.scalar(select(Product.id).where(Product.title == data["title"]).limit(1))
            if existing is not None:
                continue
            product = Product(**data, slug=unique_product_slug(db, data["title"]))
            db.add(product)
            db.flush()
        db.commit()
    finally:
        db.close()


if __name__ == "__main__":
    seed_database()
